"""Split an existing instruction file into a slim AGENTS.md plus modules, without losing a line.

Steps: plan (read-only), decide (guided answers to the plan, or edit plan.yaml by hand), apply (backup, then write into the migration folder), verify (every
original line is still present), review (the person approves the exact files), switch (install
the reviewed slim file after confirmation), restore.
Nothing outside the migration folder is written except by switch and restore, and both check
the target's hash first and copy it aside before writing.
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import re
import shutil
import subprocess
import sys
import time
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

import yaml

MARKER_PREFIX = "<!-- Generated by agent-context-router migrate"
TODO_TRIGGER = "TODO: when should the agent load this?"
MODULE_MIN_BYTES = 1200
MANAGED_BLOCKS = {"<!-- bpm:start -->": "bpm"}
SAFETY_WORDS = re.compile(r"\b(never|always|before|must|don't|do not)\b", re.IGNORECASE)
SECRET_PATTERNS = {
    "GitHub token": re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}"),
    "OpenAI-style key": re.compile(r"\bsk-[A-Za-z0-9_-]{20,}"),
    "Slack token": re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}"),
    "AWS access key": re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    "private key": re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    "password or token assignment": re.compile(r"(?i)\b(password|passwd|secret|api[_-]?key|token)\s*[:=]\s*\S{8,}"),
}


class MigrateError(Exception):
    pass


@dataclass
class Section:
    heading: str
    text: str

    @property
    def is_preamble(self) -> bool:
        return self.heading == ""

    @property
    def managed_by(self) -> str:
        return next((tool for marker, tool in MANAGED_BLOCKS.items() if marker in self.text), "")


def sha256(data: str | bytes) -> str:
    if isinstance(data, str):
        data = data.encode()
    return hashlib.sha256(data).hexdigest()


def _headings(lines: list[str]) -> list[tuple[int, int]]:
    out, fence = [], False
    for i, line in enumerate(lines):
        if line.lstrip().startswith("```"):
            fence = not fence
            continue
        m = re.match(r"^(#{1,6}) \S", line)
        if m and not fence:
            out.append((i, len(m.group(1))))
    return out


def split_sections(text: str) -> list[Section]:
    lines = text.split("\n")
    heads = _headings(lines)
    counts = Counter(level for _, level in heads)
    level = next((lv for lv in range(1, 7) if counts.get(lv, 0) >= 2), None)
    if level is None:
        return [Section("", text)]
    starts = [i for i, lv in heads if lv == level]
    sections = []
    if starts[0] > 0:
        sections.append(Section("", "\n".join(lines[: starts[0]])))
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        heading = lines[start].lstrip("#").strip()
        sections.append(Section(heading, "\n".join(lines[start:end])))
    return sections


def slugify(heading: str, taken: set[str]) -> str:
    base = re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-") or "section"
    slug, n = base, 2
    while slug in taken:
        slug, n = f"{base}-{n}", n + 1
    taken.add(slug)
    return slug


def secret_warnings(text: str) -> list[str]:
    found = []
    for n, line in enumerate(text.split("\n"), 1):
        for name, pattern in SECRET_PATTERNS.items():
            if pattern.search(line):
                found.append(f"line {n}: looks like a {name}. Remove it from the source before migrating; the migration folder keeps a copy.")
    return found


def safety_lines(text: str) -> list[str]:
    out = []
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith(("- ", "* ")) and SAFETY_WORDS.search(stripped) and len(stripped) <= 200:
            out.append(stripped)
    return out[:5]


def _ensure_empty_dir(folder: Path) -> None:
    if folder.exists() and any(folder.iterdir()):
        raise MigrateError(f"{folder} isn't empty. Choose a new folder so nothing in it gets overwritten.")
    folder.mkdir(parents=True, exist_ok=True)


def plan(source: Path, folder: Path) -> dict:
    source = source.expanduser().resolve()
    if not source.is_file():
        raise MigrateError(f"No file at {source}")
    folder = folder.expanduser().resolve()
    if folder == source.parent or source.is_relative_to(folder):
        raise MigrateError("Use a migration folder separate from the source file's folder.")
    text = source.read_text()
    _ensure_empty_dir(folder)
    taken: set[str] = set()
    entries = []
    for s in split_sections(text):
        sid = "preamble" if s.is_preamble else slugify(s.heading, taken)
        size = len(s.text.encode())
        keep = s.is_preamble or bool(s.managed_by) or size < MODULE_MIN_BYTES
        entry = {"id": sid, "heading": s.heading, "bytes": size, "action": "keep" if keep else "module"}
        if s.managed_by:
            entry["managed_by"] = s.managed_by
        if not keep:
            entry["trigger"] = TODO_TRIGGER
            entry["keep_lines"] = safety_lines(s.text)
        entries.append(entry)
    data = {
        "approved_by_person": False,
        "source": str(source),
        "source_sha256": sha256(text),
        "warnings": secret_warnings(text) + [
            f"{e['heading'] or 'The text before the first heading'} holds a block that {e['managed_by']} rewrites, so it stays in the always-loaded file."
            for e in entries if e.get("managed_by")
        ],
        "sections": entries,
    }
    _save_plan(folder, data)
    return data


PLAN_HEADER = (
    "# Migration plan. Answer it with `migrate decide`, or edit it by hand, before running apply.\n"
    "# action: keep (stays in the always-loaded file) or module (loaded on demand).\n"
    "# Every module needs a trigger: the moment the agent should load it, e.g. \"Before any adb command\".\n"
    "# keep_lines are copied into the always-loaded file so a rule still holds if its module never loads.\n"
    "# decided marks the sections answered in decide, so it can pick up where you left off.\n"
    "# When you've read every section's action and trigger, set approved_by_person: true. An agent shouldn't set it for you.\n"
)


def _save_plan(folder: Path, data: dict) -> None:
    tmp = folder / "plan.yaml.tmp"
    tmp.write_text(PLAN_HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=1000))
    tmp.replace(folder / "plan.yaml")


def _load_plan(folder: Path) -> dict:
    path = folder / "plan.yaml"
    if not path.is_file():
        raise MigrateError(f"No plan.yaml in {folder}. Run plan first.")
    return yaml.safe_load(path.read_text())


def _validate_plan(data: dict, sections: list[Section]) -> None:
    entries = data.get("sections") or []
    if len(entries) != len(sections):
        raise MigrateError("The plan's sections no longer match the source. Run plan again in a new folder.")
    problems, ids = [], set()
    for entry, section in zip(entries, sections):
        if entry.get("heading", "") != section.heading:
            problems.append(f"{entry.get('id')}: heading changed in the plan; edit only action, trigger, id and keep_lines")
        if entry["id"] in ids or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", str(entry["id"])):
            problems.append(f"{entry['id']}: ids must be unique, lowercase letters, digits and dashes")
        ids.add(entry["id"])
        action = entry.get("action")
        if action not in ("keep", "module"):
            problems.append(f"{entry['id']}: action must be keep or module")
        if action == "module":
            if section.is_preamble:
                problems.append("preamble: the text before the first heading stays in the always-loaded file")
            if section.managed_by:
                problems.append(f"{entry['id']}: holds a block that {section.managed_by} rewrites in AGENTS.md, so it stays in the always-loaded file")
            trigger = str(entry.get("trigger") or "").strip()
            if not trigger or trigger == TODO_TRIGGER:
                problems.append(f"{entry['id']}: needs a trigger")
    if data.get("approved_by_person") is not True:
        problems.append("approved_by_person isn't true. Read each section's action and trigger, then set it in plan.yaml")
    if problems:
        raise MigrateError("The plan isn't ready:\n- " + "\n- ".join(problems))


class Paused(Exception):
    pass


def _preview(section: Section, lines: int = 6) -> str:
    body = [l for l in section.text.split("\n")[1:] if l.strip()][:lines]
    return "\n".join("    " + l for l in body)


def _ask_choice(ask, question: str, choices: str, default: str) -> str:
    while True:
        answer = ask(question).strip().lower()
        if answer == "q":
            raise Paused
        if not answer:
            return default
        if answer[:1] in choices:
            return answer[:1]


def _ask_module(ask, show, entry: dict, section: Section) -> None:
    current = str(entry.get("trigger") or "").strip()
    has_trigger = bool(current) and current != TODO_TRIGGER
    while True:
        hint = f' (Enter keeps "{current}")' if has_trigger else ""
        answer = ask(f"When should the agent load it? Start with \"Before\" when order matters{hint}: ").strip()
        if answer.lower() == "q":
            raise Paused
        if answer:
            entry["trigger"] = answer
            break
        if has_trigger:
            break
        show("A module needs a trigger, for example \"Before any adb command\" or \"Writing a PR description\".")
    candidates = entry.get("keep_lines")
    if candidates is None:
        candidates = safety_lines(section.text)
    kept = []
    if candidates:
        show("These rules could stay loaded, so they hold even if the module never loads:")
    for rule in candidates:
        if _ask_choice(ask, f"  Keep loaded: {rule}  [Y/n/q] ", "yn", "y") == "y":
            kept.append(rule)
    entry["keep_lines"] = kept


def decide(folder: Path, ask, show=print, revisit: bool = False) -> dict:
    folder = folder.expanduser().resolve()
    data = _load_plan(folder)
    source = Path(data["source"])
    if not source.is_file():
        raise MigrateError(f"The source {source} is gone.")
    text = source.read_text()
    if sha256(text) != data["source_sha256"]:
        raise MigrateError(f"{source} changed since the plan. Run plan again in a new folder.")
    sections = split_sections(text)
    entries = data["sections"]
    if len(entries) != len(sections):
        raise MigrateError("The plan's sections no longer match the source. Run plan again in a new folder.")
    pairs = list(zip(entries, sections))
    if revisit:
        for entry in entries:
            entry.pop("decided", None)
    for entry, section in pairs:
        if section.managed_by:
            entry["action"] = "keep"
    data["approved_by_person"] = False
    _save_plan(folder, data)

    try:
        suggested = [(e, s) for e, s in pairs if e["action"] == "module" and not e.get("decided")]
        if suggested:
            show(f"{len(suggested)} sections are suggested as modules. For each one: keep it loaded, or make it a module and say when it loads. Type q at any prompt to stop; your answers so far are saved.")
        for n, (entry, section) in enumerate(suggested, 1):
            show(f"\n[{n}/{len(suggested)}] {section.heading} ({entry['bytes']:,} bytes)\n{_preview(section)}")
            if _ask_choice(ask, "Make this a module, or keep it loaded? [M/k/q] ", "mk", "m") == "k":
                entry["action"] = "keep"
            else:
                entry["action"] = "module"
                _ask_module(ask, show, entry, section)
            entry["decided"] = True
            _save_plan(folder, data)

        kept = [(e, s) for e, s in pairs if e["action"] == "keep" and not s.is_preamble and not s.managed_by and not e.get("decided")]
        if kept:
            show(f"\nThese {len(kept)} sections stay loaded on every turn:")
            for n, (entry, _) in enumerate(kept, 1):
                show(f"  {n}. {entry['heading']} ({entry['bytes']:,} bytes)")
            while True:
                answer = ask("Move any of these to a module? Type their numbers separated by spaces, or press Enter for none: ").strip()
                if answer.lower() == "q":
                    raise Paused
                picks = answer.replace(",", " ").split()
                if all(p.isdigit() and 1 <= int(p) <= len(kept) for p in picks):
                    break
                show(f"Use numbers from 1 to {len(kept)}.")
            chosen = {int(p) for p in picks}
            for n, (entry, section) in enumerate(kept, 1):
                if n in chosen:
                    show(f"\n{section.heading} ({entry['bytes']:,} bytes)\n{_preview(section)}")
                    entry["action"] = "module"
                    entry.setdefault("trigger", TODO_TRIGGER)
                    _ask_module(ask, show, entry, section)
                entry["decided"] = True
                _save_plan(folder, data)
        for entry, section in pairs:
            if section.is_preamble or section.managed_by:
                entry["decided"] = True
        _save_plan(folder, data)
    except Paused:
        _save_plan(folder, data)
        return {"status": "paused"}

    missing = [e["id"] for e in entries if e["action"] == "module" and str(e.get("trigger") or "").strip() in ("", TODO_TRIGGER)]
    if missing:
        show("These modules still need a trigger: " + ", ".join(missing) + ". Run decide --revisit, or set them in plan.yaml.")
        return {"status": "incomplete", "missing": missing}

    modules = [e for e in entries if e["action"] == "module"]
    kept_bytes = sum(e["bytes"] for e in entries if e["action"] == "keep")
    show(f"\nYour split: {len(entries) - len(modules)} sections stay loaded (about {kept_bytes:,} bytes before the module list), {len(modules)} become modules.")
    for e in modules:
        show(f"- {e['id']}: {e['trigger']}")
        for rule in e.get("keep_lines") or []:
            show(f"    stays loaded: {rule.lstrip('-* ').strip()}")
    try:
        approved = _ask_choice(ask, "Approve this split? [y/N] ", "yn", "n") == "y"
    except Paused:
        approved = False
    if not approved:
        show("Not approved. Your answers are saved in plan.yaml; run decide again, or edit it and set approved_by_person: true.")
        return {"status": "not approved"}
    data["approved_by_person"] = True
    _save_plan(folder, data)
    return {"status": "approved", "modules": len(modules)}


def _module_text(section: Section, source: Path) -> str:
    return f"<!-- Module from {source.name}, copied word for word by agent-context-router migrate. -->\n\n{section.text.strip(chr(10))}\n"


def _slim_text(data: dict, sections: list[Section], folder: Path) -> str:
    source = Path(data["source"])
    marker = f"{MARKER_PREFIX} from {source} (sha256 {data['source_sha256'][:12]}). Edit the modules and this file in {folder}. -->"
    parts = [marker, ""]
    modules = []
    for entry, section in zip(data["sections"], sections):
        if entry["action"] == "keep":
            parts.append(section.text.strip("\n"))
            parts.append("")
        else:
            modules.append((entry, section))
    if modules:
        lines = [
            "## Modules",
            "Load a module before the work its trigger names, with the agent-context-router `load_module` tool "
            "(argument `id`). If that tool isn't available, read the file directly from "
            f"`{folder / 'modules'}/<id>.md`. A rule listed here still applies when its module isn't loaded.",
            "",
        ]
        for entry, _ in modules:
            lines.append(f"- `{entry['id']}`: {entry['trigger'].strip()}")
            for rule in entry.get("keep_lines") or []:
                lines.append(f"  - {rule.lstrip('-* ').strip()}")
        parts.append("\n".join(lines))
        parts.append("")
    return "\n".join(parts).rstrip("\n") + "\n"


def _git(folder: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(folder), *args], capture_output=True, text=True)


def _commit(folder: Path, paths: list[str], message: str) -> str:
    if shutil.which("git") is None:
        return "git not found; skipped the commit"
    if not (folder / ".git").exists():
        _git(folder, "init", "-q")
    _git(folder, "add", "--", *paths)
    result = _git(folder, "commit", "-q", "-m", message)
    if result.returncode != 0:
        return "commit skipped: " + (result.stderr.strip() or result.stdout.strip())[:200]
    return ""


def apply(folder: Path) -> dict:
    folder = folder.expanduser().resolve()
    data = _load_plan(folder)
    source = Path(data["source"])
    if not source.is_file():
        raise MigrateError(f"The source {source} is gone.")
    text = source.read_text()
    if sha256(text) != data["source_sha256"]:
        raise MigrateError(f"{source} changed since the plan. Run plan again in a new folder.")
    sections = split_sections(text)
    _validate_plan(data, sections)
    notes = []

    backup = folder / "backup"
    original = backup / source.name
    manifest_path = backup / "manifest.json"
    if original.exists():
        if sha256(original.read_bytes()) != data["source_sha256"]:
            raise MigrateError(f"{original} doesn't match the source. Leaving it alone; use a new folder.")
    else:
        backup.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, original)
        stat = source.stat()
        manifest = {"source": str(source), "sha256": data["source_sha256"], "bytes": stat.st_size, "mtime": stat.st_mtime, "backed_up_at": time.time()}
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
        note = _commit(folder, ["backup", "plan.yaml"], f"Back up {source.name} before migrating")
        if note:
            notes.append(note)

    modules_dir = folder / "modules"
    slim_path = folder / "AGENTS.md"
    if slim_path.exists() and not slim_path.read_text().startswith(MARKER_PREFIX):
        raise MigrateError(f"{slim_path} wasn't written by migrate. Leaving the folder alone.")
    previous = sorted(modules_dir.iterdir()) if modules_dir.exists() else []
    foreign = [p for p in previous if not (p.suffix == ".md" and p.read_text().startswith("<!-- Module from "))]
    if foreign:
        raise MigrateError(f"{foreign[0]} wasn't written by migrate. Leaving the folder alone.")
    for old in previous:
        old.unlink()
    (folder / "review.json").unlink(missing_ok=True)
    modules_dir.mkdir(exist_ok=True)

    registry = {"repos": {"context": {"path": "."}}, "modules": []}
    for entry, section in zip(data["sections"], sections):
        if entry["action"] == "module":
            (modules_dir / f"{entry['id']}.md").write_text(_module_text(section, source))
            registry["modules"].append({"id": entry["id"], "repo": "context", "file": f"modules/{entry['id']}.md", "trigger": entry["trigger"].strip()})
    slim_path.write_text(_slim_text(data, sections, folder))
    (folder / "modules.yaml").write_text(
        "# Registry for agent-context-router. Set ACR_REGISTRY to this file.\n"
        + yaml.safe_dump(registry, sort_keys=False, allow_unicode=True, width=1000)
    )
    note = _commit(folder, ["AGENTS.md", "modules", "modules.yaml", "plan.yaml"], f"Split {source.name} into a slim file and {len(registry['modules'])} modules")
    if note and "nothing to commit" not in note:
        notes.append(note)
    result = verify(folder)
    result["notes"] = notes
    return result


def verify(folder: Path) -> dict:
    folder = folder.expanduser().resolve()
    manifest_path = folder / "backup" / "manifest.json"
    if not manifest_path.is_file():
        raise MigrateError(f"No backup in {folder}. Run apply first.")
    manifest = json.loads(manifest_path.read_text())
    original = (folder / "backup" / Path(manifest["source"]).name).read_text()
    if sha256(original) != manifest["sha256"]:
        raise MigrateError("The backup copy doesn't match its recorded hash.")
    slim = (folder / "AGENTS.md").read_text()
    registry = yaml.safe_load((folder / "modules.yaml").read_text())
    module_texts = []
    problems = []
    for m in registry.get("modules", []):
        path = folder / m["file"]
        if not path.is_file():
            problems.append(f"module file missing: {m['file']}")
            continue
        module_texts.append(path.read_text())
        if f"`{m['id']}`" not in slim:
            problems.append(f"module {m['id']} isn't listed in AGENTS.md")
    have = Counter(line.strip() for text in [slim, *module_texts] for line in text.split("\n") if line.strip())
    need = Counter(line.strip() for line in original.split("\n") if line.strip())
    missing = need - have
    for line, count in missing.items():
        problems.append(f"missing {count}x: {line[:120]}")
    return {"ok": not problems, "problems": problems, "lines_checked": sum(need.values()), "modules": len(module_texts)}


def _reviewed_files(folder: Path) -> list[Path]:
    return [folder / "AGENTS.md", folder / "modules.yaml", *sorted((folder / "modules").glob("*.md"))]


def content_hash(folder: Path) -> str:
    h = hashlib.sha256()
    for path in _reviewed_files(folder):
        h.update(f"{path.relative_to(folder)}\0{sha256(path.read_bytes())}\n".encode())
    return h.hexdigest()


def summary(folder: Path, diff: bool = False) -> str:
    folder = folder.expanduser().resolve()
    manifest = json.loads((folder / "backup" / "manifest.json").read_text())
    original = (folder / "backup" / Path(manifest["source"]).name).read_text()
    slim = (folder / "AGENTS.md").read_text()
    registry = yaml.safe_load((folder / "modules.yaml").read_text())
    data = _load_plan(folder)
    kept = [e["heading"] or "(text before the first heading)" for e in data["sections"] if e["action"] == "keep"]
    lines = [
        f"Source: {manifest['source']}",
        f"Always loaded: {len(slim.encode()):,} bytes, from {len(original.encode()):,}",
        f"Kept sections ({len(kept)}): " + "; ".join(kept),
        f"Modules ({len(registry.get('modules', []))}):",
    ]
    keep_lines = {e["id"]: e.get("keep_lines") or [] for e in data["sections"]}
    for m in registry.get("modules", []):
        size = (folder / m["file"]).stat().st_size
        lines.append(f"- {m['id']} ({size:,} bytes): {m['trigger']}")
        for rule in keep_lines.get(m["id"], []):
            lines.append(f"    stays loaded: {rule.lstrip('-* ').strip()}")
    if diff:
        lines.append("")
        lines.extend(
            difflib.unified_diff(
                original.splitlines(), slim.splitlines(), f"{manifest['source']} (now)", "AGENTS.md (after switch)", lineterm=""
            )
        )
    return "\n".join(lines)


def review(folder: Path, confirm, diff: bool = False, show=print) -> dict:
    folder = folder.expanduser().resolve()
    result = verify(folder)
    if not result["ok"]:
        raise MigrateError("verify failed; fix the files before review:\n- " + "\n- ".join(result["problems"]))
    show(summary(folder, diff=diff))
    if not confirm(f"Approve these files in {folder} for switch?"):
        return {"status": "not approved"}
    record = {"content_sha256": content_hash(folder), "files": [str(p.relative_to(folder)) for p in _reviewed_files(folder)], "reviewed_at": time.time()}
    (folder / "review.json").write_text(json.dumps(record, indent=2) + "\n")
    note = _commit(folder, ["review.json"], "Record the review")
    return {"status": "approved", "content_sha256": record["content_sha256"], "notes": [note] if note else []}


def _copy_aside(target: Path, folder: Path, label: str) -> Path:
    dest = folder / "backup" / f"{target.name}.{label}-{time.strftime('%Y%m%d-%H%M%S')}"
    shutil.copy2(target, dest)
    return dest


def switch(folder: Path, confirm, diff: bool = False, show=print) -> dict:
    folder = folder.expanduser().resolve()
    result = verify(folder)
    if not result["ok"]:
        raise MigrateError("verify failed; not switching:\n- " + "\n- ".join(result["problems"]))
    review_path = folder / "review.json"
    if not review_path.is_file():
        raise MigrateError(f"No review yet. Run: agent-context-router migrate review {folder}")
    if json.loads(review_path.read_text()).get("content_sha256") != content_hash(folder):
        raise MigrateError(f"The files changed after the review. Run review again: agent-context-router migrate review {folder}")
    manifest = json.loads((folder / "backup" / "manifest.json").read_text())
    target = Path(manifest["source"])
    slim = (folder / "AGENTS.md").read_text()
    if not target.is_file():
        raise MigrateError(f"{target} is gone; not switching.")
    current = sha256(target.read_bytes())
    if current == sha256(slim):
        return {"target": str(target), "status": "already switched"}
    if current != manifest["sha256"]:
        raise MigrateError(f"{target} changed since the backup. Run plan again in a new folder so those changes are kept.")
    show(summary(folder, diff=diff))
    if not confirm(f"Replace {target} with the reviewed slim file from {folder}?"):
        return {"target": str(target), "status": "cancelled"}
    aside = _copy_aside(target, folder, "before-switch")
    tmp = target.with_name(target.name + ".acr-tmp")
    tmp.write_text(slim)
    tmp.replace(target)
    return {"target": str(target), "status": "switched", "copy": str(aside), "registry": str(folder / "modules.yaml")}


def restore(folder: Path, confirm, force: bool = False) -> dict:
    folder = folder.expanduser().resolve()
    manifest_path = folder / "backup" / "manifest.json"
    if not manifest_path.is_file():
        raise MigrateError(f"No backup in {folder}.")
    manifest = json.loads(manifest_path.read_text())
    target = Path(manifest["source"])
    original = folder / "backup" / target.name
    if sha256(original.read_bytes()) != manifest["sha256"]:
        raise MigrateError("The backup copy doesn't match its recorded hash; not restoring.")
    slim_hash = sha256((folder / "AGENTS.md").read_bytes()) if (folder / "AGENTS.md").exists() else ""
    aside = None
    if target.exists():
        current = sha256(target.read_bytes())
        if current == manifest["sha256"]:
            return {"target": str(target), "status": "already the original"}
        if current != slim_hash and not force:
            raise MigrateError(f"{target} was edited after the switch. Pass --force to restore anyway; the edited file is copied aside first.")
        if not confirm(f"Restore the original {target.name} to {target}?"):
            return {"target": str(target), "status": "cancelled"}
        aside = _copy_aside(target, folder, "before-restore")
    elif not confirm(f"Restore the original {target.name} to {target}?"):
        return {"target": str(target), "status": "cancelled"}
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(original, target)
    return {"target": str(target), "status": "restored", "copy": str(aside) if aside else ""}


def _ask_line(question: str) -> str:
    try:
        return input(question)
    except EOFError:
        return "q"


def _ask(question: str) -> bool:
    if not sys.stdin.isatty():
        return False
    try:
        return input(f"{question} [y/N] ").strip().lower() in ("y", "yes")
    except EOFError:
        return False


def cli(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="agent-context-router migrate", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="step", required=True)
    p = sub.add_parser("plan", help="read the source and write plan.yaml into a new folder")
    p.add_argument("source", type=Path)
    p.add_argument("folder", type=Path)
    d = sub.add_parser("decide", help="answer the plan one section at a time, in the terminal")
    d.add_argument("folder", type=Path)
    d.add_argument("--revisit", action="store_true", help="ask about every section again, including ones already answered")
    for name, text in (("apply", "back up the source, then write modules, AGENTS.md and modules.yaml"), ("verify", "check that every original line is still present")):
        sub.add_parser(name, help=text).add_argument("folder", type=Path)
    v = sub.add_parser("review", help="show what switch would install and record your approval of those exact files")
    v.add_argument("folder", type=Path)
    v.add_argument("--diff", action="store_true", help="also show the diff from your current file")
    v.add_argument("--yes", action="store_true")
    s = sub.add_parser("switch", help="install the reviewed slim file at the source path")
    s.add_argument("folder", type=Path)
    s.add_argument("--diff", action="store_true", help="also show the diff from your current file")
    s.add_argument("--yes", action="store_true")
    r = sub.add_parser("restore", help="put the original file back")
    r.add_argument("folder", type=Path)
    r.add_argument("--yes", action="store_true")
    r.add_argument("--force", action="store_true", help="restore even if the file was edited after the switch")
    args = parser.parse_args(argv)
    confirm = (lambda _q: True) if getattr(args, "yes", False) else _ask
    try:
        if args.step == "plan":
            data = plan(args.source, args.folder)
            mods = sum(1 for e in data["sections"] if e["action"] == "module")
            print(f"Wrote {args.folder / 'plan.yaml'}: {len(data['sections'])} sections, {mods} suggested as modules. Nothing else was written.")
            for w in data["warnings"]:
                print(f"warning: {w}")
            print(f"Next: agent-context-router migrate decide {args.folder}  (or edit plan.yaml by hand and set approved_by_person: true), then apply.")
            return 0
        if args.step == "decide":
            if not sys.stdin.isatty():
                raise MigrateError("decide asks you questions, so it needs a terminal. To answer without one, edit plan.yaml by hand.")
            result = decide(args.folder, _ask_line, revisit=args.revisit)
            if result["status"] == "paused":
                print("Paused. Your answers are saved; run decide again to pick up where you left off.")
                return 1
            if result["status"] != "approved":
                return 1
            if _ask("Run apply now?"):
                result = apply(args.folder)
                for n in result["notes"]:
                    print(f"note: {n}")
                if result["ok"]:
                    print(f"verify passed: {result['lines_checked']} lines of the original found, {result['modules']} modules.")
                    print(f"Next: read {args.folder / 'AGENTS.md'}, then run review. The source hasn't been changed.")
                    return 0
                print("verify failed:\n- " + "\n- ".join(result["problems"]))
                return 1
            print(f"Approved. Next: agent-context-router migrate apply {args.folder}")
            return 0
        if args.step == "apply":
            result = apply(args.folder)
            for n in result["notes"]:
                print(f"note: {n}")
        elif args.step == "verify":
            result = verify(args.folder)
        elif args.step == "review":
            result = review(args.folder, confirm, diff=args.diff)
            for n in result.get("notes", []):
                print(f"note: {n}")
            if result["status"] == "approved":
                print(f"Approved. Next: agent-context-router migrate switch {args.folder}")
                return 0
            print("Not approved; nothing recorded.")
            return 1
        elif args.step == "switch":
            result = switch(args.folder, confirm, diff=args.diff)
            print(json.dumps(result, indent=2))
            if result["status"] == "switched":
                print(f"Register the router with ACR_REGISTRY={result['registry']} (see README). To undo: agent-context-router migrate restore {args.folder}")
            return 0 if result["status"] in ("switched", "already switched") else 1
        else:
            result = restore(args.folder, confirm, force=args.force)
            print(json.dumps(result, indent=2))
            return 0 if result["status"] in ("restored", "already the original") else 1
        if result["ok"]:
            print(f"verify passed: {result['lines_checked']} lines of the original found, {result['modules']} modules.")
            if args.step == "apply":
                print(f"Next: read {args.folder / 'AGENTS.md'}, then run review. The source hasn't been changed.")
            return 0
        print("verify failed:\n- " + "\n- ".join(result["problems"]))
        return 1
    except MigrateError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
